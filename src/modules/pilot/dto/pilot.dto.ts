import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsBoolean,
  IsNotEmpty,
  IsString,
  ValidateNested,
} from 'class-validator';
import { LocationDto } from 'src/common/dto/common.dto';

export class DrivingLicenseDto {
  @ApiProperty({ description: 'Driving license number' })
  @IsNotEmpty({ message: 'Driving license number is required' })
  @IsString()
  drivingLicenseNumber: string;

  @ApiProperty({ description: 'Date of birth' })
  @IsNotEmpty({ message: 'Date of birth is required' })
  @IsString()
  dob: string;
}

export class VehicleRcDto {
  @ApiProperty({ description: 'Vehicle registration number' })
  @IsNotEmpty({ message: 'Vehicle registration number is required' })
  @IsString()
  registrationNumber: string;
}

export class PancardDto {
  @ApiProperty({ description: 'Pan card number' })
  @IsNotEmpty({ message: 'Pan card number is required' })
  @IsString()
  panNumber: string;
}

export class AadhaarNumberDto {
  @ApiProperty({ description: 'Aadhaar number' })
  @IsNotEmpty({ message: 'Aadhaar number is required' })
  @IsString()
  aadhaarNumber: string;
}

export class VerifyAadhaarDto {
  @ApiProperty({ description: 'OTP generated by Cashfree API' })
  @IsNotEmpty({ message: 'OTP is required' })
  @IsString()
  otp: string;

  @ApiProperty({ description: 'Ref id generated by Cashfree API' })
  @IsNotEmpty({ message: 'Ref id is required' })
  @IsString()
  ref_id: string;

  @ApiProperty({ description: 'Aadhaar number' })
  @IsNotEmpty({ message: 'Aadhaar number is required' })
  @IsString()
  aadhaarNumber: string;
}

export class BeOnlineDto {
  @ApiProperty({ description: 'Make driver available' })
  @IsNotEmpty({ message: 'Is available is required' })
  @IsBoolean()
  onlineStatus: boolean;

  @ApiProperty({
    description: 'Current Location in latitude and longitude',
  })
  @IsNotEmpty()
  @ValidateNested()
  @Type(() => LocationDto)
  currentLocation: LocationDto;
}

export class AcceptRideDto {
  @ApiProperty({ description: 'Booking id' })
  @IsNotEmpty({ message: 'Booking id is required' })
  @IsString()
  bookingId: string;
}

export class StartRideDto extends AcceptRideDto {
  @ApiProperty({ description: 'Booking id' })
  @IsNotEmpty({ message: 'Booking id is required' })
  @IsString()
  bookingCode: string;
}
